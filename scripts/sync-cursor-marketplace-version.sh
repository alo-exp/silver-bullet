#!/usr/bin/env bash
# Align the Cursor marketplace manifests with the release version.
#
#   scripts/sync-cursor-marketplace-version.sh [version]
#       Set the silver-bullet entry of this repository's .cursor-plugin/marketplace.json to
#       the version of .cursor-plugin/plugin.json ([version], when given, must equal it),
#       pin it to the release commit, and regenerate the Cursor package. Nothing leaves the
#       machine; commit the result with the release.
#   scripts/sync-cursor-marketplace-version.sh --publish [version]
#       Publish that version to the unified agent-plugins marketplace (defaults to
#       alo-labs/agent-plugins), pinned to the commit of the release tag v<version>: commit
#       only .cursor-plugin/marketplace.json there, push it and confirm the push. The release
#       runs this through scripts/sync-release-marketplace-versions.sh --publish.
#
# Exit 0 = in sync or synced; exit 1 = jq missing, invalid JSON, or a precondition failed.

set -euo pipefail
trap 'exit 1' ERR

repo_root=$(cd "$(dirname "$0")/.." && pwd)
# shellcheck source=scripts/lib/agent-plugins-common.sh
source "${repo_root}/scripts/lib/agent-plugins-common.sh"
plugin_json="$repo_root/.cursor-plugin/plugin.json"
marketplace_json="$repo_root/.cursor-plugin/marketplace.json"
marketplace_rel=.cursor-plugin/marketplace.json
package_manifest="$repo_root/plugins/silver-bullet/.cursor-plugin/plugin.json"
marketplace_repo_url="$(resolve_agent_plugins_repo_url cursor)"
marketplace_repo_root="${AGENT_PLUGINS_REPO_ROOT:-${CURSOR_MARKETPLACE_REPO_ROOT:-}}"

command -v jq >/dev/null || { echo "jq required"; exit 1; }
agent_plugins_parse_sync_args "$@"
requested_version="$AGENT_PLUGINS_VERSION"


# A manifest that does not parse is a different problem from one without our entry.
require_valid_json() {
  if ! jq -e . "$1" >/dev/null 2>&1; then
    echo "ERROR: $1 is not valid JSON" >&2
    exit 1
  fi
}

# update_marketplace_plugin_source MANIFEST VERSION REF SHA: pin the silver-bullet entry to the
# release tag (ref) and, once the tag exists, to its commit (sha; empty drops it).
update_marketplace_plugin_source() {
  local manifest="$1"
  local version="$2"
  local source_ref="$3"
  local release_sha="$4"
  # Nothing to pin without a silver-bullet entry: fail instead of reporting a no-op as synced.
  if ! jq -e '[.plugins[]? | select(.name=="silver-bullet")] | length > 0' "$manifest" >/dev/null; then
    echo "ERROR: $manifest has no silver-bullet entry to sync" >&2
    exit 1
  fi
  # shellcheck disable=SC2016  # $v, $ref, $sha and $path are jq variables
  agent_plugins_json_rewrite "$manifest" --arg v "$version" --arg ref "$source_ref" --arg sha "$release_sha" --arg path "plugins/silver-bullet" '
    (.plugins[] | select(.name=="silver-bullet") | .version) = $v
    | (.plugins[] | select(.name=="silver-bullet") | .source.ref) = $ref
    | (.plugins[] | select(.name=="silver-bullet") | .source) |= (if $sha == "" then del(.sha) else .sha = $sha end)
    | (.plugins[] | select(.name=="silver-bullet") | .source.path) = $path
  '
}

# The package manifest is generated by scripts/sync-cursor-package.sh from .cursor-plugin.
require_package_version() {
  local package_v
  package_v=$(jq -r '.version' "$package_manifest")
  if [[ "$package_v" != "$1" ]]; then
    echo "ERROR: plugins/silver-bullet/.cursor-plugin/plugin.json is $package_v but release version is $1" >&2
    exit 1
  fi
}

current_plugin_v=$(jq -r '.version' "$plugin_json")
if [[ -n "$requested_version" ]]; then
  plugin_v="${requested_version#v}"
  if [[ "$current_plugin_v" != "$plugin_v" ]]; then
    echo "ERROR: $plugin_json is $current_plugin_v but the release version is $plugin_v. Bump the plugin manifest first." >&2
    exit 1
  fi
else
  plugin_v="$current_plugin_v"
fi
require_valid_json "$marketplace_json"
market_v=$(jq -r '.plugins[] | select(.name=="silver-bullet") | .version' "$marketplace_json")

if [[ "$AGENT_PLUGINS_PUBLISH" != "1" ]]; then
  update_marketplace_plugin_source "$marketplace_json" "$plugin_v" \
    "v${plugin_v}" "$(agent_plugins_tag_commit_if_any "$repo_root" "$plugin_v")"
  if [[ "$plugin_v" == "$market_v" ]]; then
    echo "✓ Versions already in sync: $plugin_v"
  else
    echo "✓ Updated in-repo marketplace.json: $market_v → $plugin_v"
  fi

  cursor_package_sync_script="$repo_root/scripts/sync-cursor-package.sh"
  if [[ -x "$cursor_package_sync_script" ]]; then
    bash "$cursor_package_sync_script" >/dev/null
  else
    echo "ERROR: Cursor package sync script not found or not executable: $cursor_package_sync_script" >&2
    exit 1
  fi
  require_package_version "$plugin_v"
  printf "\nThis repository's Cursor marketplace manifest is at v%s.\n" "$plugin_v"
  exit 0
fi

publish_marketplace_repo() {
  local root="$1"
  local version="$2"
  local release_sha="$3"
  local manifest="$root/$marketplace_rel"
  local remote_before
  local remote_after

  [[ -d "$root/.git" ]] || {
    echo "ERROR: marketplace repo root is not a git repository: $root" >&2
    exit 1
  }
  [[ -f "$manifest" ]] || {
    echo "ERROR: Cursor marketplace manifest not found in repo: $manifest" >&2
    exit 1
  }

  require_valid_json "$manifest"
  # Batch runs (AGENT_PLUGINS_SKIP_PUSH=1) are checked once by the release wrapper.
  [[ "${AGENT_PLUGINS_SKIP_PUSH:-0}" == "1" ]] || agent_plugins_check_publishable "$root"
  agent_plugins_require_clean_path "$root" "$marketplace_rel"
  remote_before=$(jq -r '.plugins[] | select(.name=="silver-bullet") | .version' "$manifest")
  # The unified marketplace always ships the tagged release commit.
  update_marketplace_plugin_source "$manifest" "$version" "v${version}" "$release_sha"

  if git -C "$root" diff --quiet -- "$marketplace_rel"; then
    echo "✓ Cursor marketplace manifest already at silver-bullet $version: $root"
    return 0
  fi

  agent_plugins_commit_paths "$root" "Bump silver-bullet Cursor manifest to $version" "$marketplace_rel"
  agent_plugins_push "$root"

  remote_after=$(jq -r '.plugins[] | select(.name=="silver-bullet") | .version' "$manifest")
  echo "✓ Updated Cursor marketplace manifest: $remote_before → $remote_after"
}

# --publish ships what the release commit carries: the in-repo manifests must already be
# aligned and the release tag must exist.
if [[ "$market_v" != "$plugin_v" ]]; then
  echo "ERROR: $marketplace_json is $market_v, not $plugin_v: run scripts/sync-cursor-marketplace-version.sh $plugin_v and commit the result before publishing" >&2
  exit 1
fi
require_package_version "$plugin_v"
release_sha="$(agent_plugins_release_tag_commit "$repo_root" "$plugin_v")"
agent_plugins_require_tag_on_origin "$repo_root" "$plugin_v"
agent_plugins_require_green_ci "$repo_root" "$plugin_v"

if [[ -n "$marketplace_repo_root" ]]; then
  publish_marketplace_repo "$marketplace_repo_root" "$plugin_v" "$release_sha"
else
  tmp_repo_root=$(mktemp -d "${TMPDIR:-/tmp}/sb-agent-plugins-cursor.XXXXXX")
  trap 'rm -rf -- "$tmp_repo_root"' EXIT
  git clone -q "$marketplace_repo_url" "$tmp_repo_root"
  publish_marketplace_repo "$tmp_repo_root" "$plugin_v" "$release_sha"
fi

if [[ "${AGENT_PLUGINS_SKIP_PUSH:-0}" == "1" ]]; then
  echo "Cursor marketplace manifest committed in the shared checkout (push pending: the release wrapper pushes every host once)."
else
cat <<EOF

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  Cursor marketplace publish complete
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
The agent-plugins Cursor manifest now offers silver-bullet v$plugin_v.
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
EOF
fi
